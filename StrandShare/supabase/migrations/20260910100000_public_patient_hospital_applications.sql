create or replace function public.can_read_patient_application_asset(p_object_name text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $fn$
  select exists (
    select 1
    from public.users actor
    join public."Hospital_Representative" representative
      on representative."User_ID" = actor.user_id
    join public."Patient_Applications" application
      on application."Patient_Picture_Path" = p_object_name
      or application."Medical_Document_Path" = p_object_name
    left join public."Patients" patient
      on patient."Patient_ID" = application."Created_Patient_ID"
    where actor.auth_user_id = auth.uid()
      and actor.is_active is distinct from false
      and public.normalize_app_role(actor.role) = 'hrepresentative'
      and (
        (
          public.normalize_flow_key(application."Status") <> 'accepted'
          and representative."Hospital_ID" = application."Hospital_ID"
        )
        or representative."Hospital_ID" = patient."Hospital_ID"
      )
  );
$fn$;

