create or replace function public.reject_patient_application(
  p_application_id bigint,
  p_actor_user_id integer,
  p_reason text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  v_application public."Patient_Applications"%rowtype;
  v_actor public.users%rowtype;
  v_hospital_name text;
  v_reason text := nullif(trim(coalesce(p_reason, '')), '');
begin
  if v_reason is null then raise exception 'A rejection reason is required'; end if;

  select * into v_actor from public.users
  where user_id = p_actor_user_id and is_active is distinct from false;
  if v_actor.user_id is null or public.normalize_app_role(v_actor.role) <> 'hrepresentative' then
    raise exception 'Only an active H-Representative can reject this application';
  end if;

  select * into v_application from public."Patient_Applications"
  where "Patient_Application_ID" = p_application_id for update;
  if v_application."Patient_Application_ID" is null then raise exception 'Application was not found'; end if;
  if public.normalize_flow_key(v_application."Status") <> 'submitted' then
    raise exception 'This application has already been decided';
  end if;
  if not exists (
    select 1 from public."Hospital_Representative" representative
    where representative."User_ID" = v_actor.user_id
      and representative."Hospital_ID" = v_application."Hospital_ID"
  ) then raise exception 'This application belongs to another hospital'; end if;

  update public."Patient_Applications" set
    "Status" = 'rejected', "Reviewed_At" = now(), "Reviewed_By" = v_actor.user_id,
    "Decision_Reason" = v_reason, "Updated_At" = now()
  where "Patient_Application_ID" = v_application."Patient_Application_ID";

  select "Hospital_Name" into v_hospital_name
  from public."Hospitals" where "Hospital_ID" = v_application."Hospital_ID";

  perform public.enqueue_smtp_email_outbox(
    'patient-application-rejected:' || v_application."Patient_Application_ID"::text,
    'Patient_Applications', v_application."Patient_Application_ID"::integer,
    'patient_application_rejected', v_application."Applicant_Email",
    'Patient application decision', 'patient_application_rejected',
    jsonb_build_object(
      'application_code', v_application."Application_Code",
      'applicant_name', concat_ws(' ', v_application."First_Name", v_application."Middle_Name", v_application."Last_Name", v_application."Suffix"),
      'hospital_name', coalesce(v_hospital_name, 'Selected hospital'),
      'decision_reason', v_reason
    ),
    v_actor.user_id
  );

  insert into public.audit_logs (user_id, action, description, user_email, resource, status, "time")
  values (
    v_actor.user_id, 'patient_application.rejected',
    format('Rejected patient application %s.', v_application."Application_Code"),
    v_actor.email, 'Patient_Applications:' || v_application."Patient_Application_ID"::text,
    'success', timezone('Asia/Manila', now())
  );

  return jsonb_build_object(
    'application_id', v_application."Patient_Application_ID",
    'application_code', v_application."Application_Code",
    'decision', 'rejected'
  );
end;
$fn$;

