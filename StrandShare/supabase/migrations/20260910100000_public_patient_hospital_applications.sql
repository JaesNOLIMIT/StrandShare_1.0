-- Admin alone publishes the global patient-application terms. Other existing
-- legal-document types keep their current role rules.
create or replace function public.guard_patient_application_global_terms_admin()
returns trigger
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  v_role text;
begin
  if new.document_type <> 'patient_application_terms' then return new; end if;
  select public.normalize_app_role(role) into v_role
  from public.users where auth_user_id = auth.uid() and is_active is distinct from false limit 1;
  if v_role not in ('admin','superadmin') then
    raise exception 'Only Admin can publish Donivra patient application terms';
  end if;
  return new;
end;
$fn$;

