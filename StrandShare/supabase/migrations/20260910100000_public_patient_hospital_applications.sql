create or replace function public.get_my_hospital_patient_application_settings()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $fn$
declare
  v_actor public.users%rowtype;
  v_hospital public."Hospitals"%rowtype;
begin
  select * into v_actor from public.users
  where auth_user_id = auth.uid() and is_active is distinct from false limit 1;
  if v_actor.user_id is null or public.normalize_app_role(v_actor.role) <> 'hrepresentative' then
    raise exception 'Only an active H-Representative can view hospital application settings';
  end if;

  select hospital.* into v_hospital
  from public."Hospitals" hospital
  join public."Hospital_Representative" representative
    on representative."Hospital_ID" = hospital."Hospital_ID"
  where representative."User_ID" = v_actor.user_id
  limit 1;

  if v_hospital."Hospital_ID" is null then raise exception 'Hospital assignment was not found'; end if;
  return jsonb_build_object(
    'hospital_id', v_hospital."Hospital_ID",
    'hospital_name', v_hospital."Hospital_Name",
    'applications_open', v_hospital."Patient_Applications_Open",
    'conditions', v_hospital."Patient_Application_Conditions",
    'requirements', v_hospital."Patient_Application_Requirements",
    'requirements_pdf_path', v_hospital."Patient_Application_PDF_Path",
    'updated_at', v_hospital."Patient_Application_Settings_Updated_At"
  );
end;
$fn$;

create or replace function public.update_my_hospital_patient_application_settings(
  p_applications_open boolean,
  p_conditions text,
  p_requirements jsonb,
  p_requirements_pdf_path text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  v_actor public.users%rowtype;
  v_hospital_id integer;
begin
  select * into v_actor from public.users
  where auth_user_id = auth.uid() and is_active is distinct from false limit 1;
  if v_actor.user_id is null or public.normalize_app_role(v_actor.role) <> 'hrepresentative' then
    raise exception 'Only an active H-Representative can update hospital application settings';
  end if;

  select representative."Hospital_ID" into v_hospital_id
  from public."Hospital_Representative" representative
  where representative."User_ID" = v_actor.user_id
  limit 1;
  if v_hospital_id is null then raise exception 'Hospital assignment was not found'; end if;
  if jsonb_typeof(coalesce(p_requirements, '[]'::jsonb)) <> 'array' then
    raise exception 'Requirements must be a list';
  end if;
  if exists (
    select 1
    from jsonb_array_elements(coalesce(p_requirements, '[]'::jsonb)) requirement
    where jsonb_typeof(requirement) <> 'string'
      or nullif(trim(requirement #>> '{}'), '') is null
      or length(requirement #>> '{}') > 500
  ) then raise exception 'Every requirement must be non-empty text of 500 characters or less'; end if;
  if jsonb_array_length(coalesce(p_requirements, '[]'::jsonb)) > 30 then
    raise exception 'A hospital can publish at most 30 application requirements';
  end if;
  if nullif(trim(coalesce(p_requirements_pdf_path,'')), '') is not null
    and split_part(trim(p_requirements_pdf_path), '/', 1) <> v_hospital_id::text
  then raise exception 'The requirements PDF must belong to your assigned hospital'; end if;
  if p_applications_open is true
    and nullif(trim(coalesce(p_conditions,'')), '') is null
  then raise exception 'Add the hospital conditions before opening applications'; end if;
  if p_applications_open is true
    and jsonb_array_length(coalesce(p_requirements, '[]'::jsonb)) = 0
  then raise exception 'Add at least one hospital requirement before opening applications'; end if;
  if p_applications_open is true
    and nullif(trim(coalesce(p_requirements_pdf_path,'')), '') is null
  then raise exception 'Upload the hospital requirements PDF before opening applications'; end if;
  if p_applications_open is true and not exists (
    select 1 from public.legal_documents document
    where document.document_type = 'patient_application_terms'
      and document.is_active is true
      and document.effective_at <= timezone('Asia/Manila', now())
  ) then raise exception 'Admin must publish the Donivra patient application terms before applications can open'; end if;

  update public."Hospitals" set
    "Patient_Applications_Open" = coalesce(p_applications_open, false),
    "Patient_Application_Conditions" = nullif(trim(coalesce(p_conditions,'')), ''),
    "Patient_Application_Requirements" = coalesce(p_requirements, '[]'::jsonb),
    "Patient_Application_PDF_Path" = nullif(trim(coalesce(p_requirements_pdf_path,'')), ''),
    "Patient_Application_Settings_Updated_At" = now(),
    "Patient_Application_Settings_Updated_By" = v_actor.user_id,
    "Updated_At" = timezone('Asia/Manila', now())
  where "Hospital_ID" = v_hospital_id;

  insert into public.audit_logs (user_id, action, description, user_email, resource, status, "time")
  values (
    v_actor.user_id, 'patient_applications.settings_updated',
    format('Updated patient application conditions for hospital_id=%s.', v_hospital_id),
    v_actor.email, 'Hospitals:' || v_hospital_id::text, 'success', timezone('Asia/Manila', now())
  );

  return public.get_my_hospital_patient_application_settings();
end;
$fn$;

revoke all on function public.get_my_hospital_patient_application_settings() from public, anon;
revoke all on function public.update_my_hospital_patient_application_settings(boolean,text,jsonb,text) from public, anon;
