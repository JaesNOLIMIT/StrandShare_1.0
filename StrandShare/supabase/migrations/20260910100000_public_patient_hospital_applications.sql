-- Called only by the patient-application Edge Function after it has verified
-- the signed-in H-Representative and created the Supabase Auth invite.
create or replace function public.finalize_patient_application_acceptance(
  p_application_id bigint,
  p_auth_user_id uuid,
  p_actor_user_id integer,
  p_patient_code text,
  p_patient_picture_path text,
  p_account_setup_url text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  v_application public."Patient_Applications"%rowtype;
  v_actor public.users%rowtype;
  v_user_id integer;
  v_patient_id integer;
  v_hospital_name text;
begin
  if nullif(trim(coalesce(p_account_setup_url, '')), '') is null then
    raise exception 'A secure account setup link is required';
  end if;

  select * into v_actor from public.users
  where user_id = p_actor_user_id and is_active is distinct from false;
  if v_actor.user_id is null or public.normalize_app_role(v_actor.role) <> 'hrepresentative' then
    raise exception 'Only an active H-Representative can accept this application';
  end if;

  select * into v_application from public."Patient_Applications"
  where "Patient_Application_ID" = p_application_id for update;
  if v_application."Patient_Application_ID" is null then raise exception 'Application was not found'; end if;
  if public.normalize_flow_key(v_application."Status") <> 'submitted' then
    raise exception 'This application has already been decided';
  end if;
  if not exists (
    select 1 from public."Hospital_Representative" representative
    where representative."User_ID" = v_actor.user_id
      and representative."Hospital_ID" = v_application."Hospital_ID"
  ) then raise exception 'This application belongs to another hospital'; end if;
  if exists (select 1 from public.users where lower(email) = v_application."Applicant_Email") then
    raise exception 'This email already belongs to an existing account';
  end if;

  insert into public.users (auth_user_id, email, role, is_active, created_at, updated_at)
  values (p_auth_user_id, v_application."Applicant_Email", 'patient', true,
    timezone('Asia/Manila', now()), timezone('Asia/Manila', now()))
  returning user_id into v_user_id;

  insert into public.user_details (
    user_id, first_name, middle_name, last_name, suffix, birthdate, gender,
    contact_number, street, barangay, city, province, region, country,
    photo_path, joined_date, created_at, updated_at
  ) values (
    v_user_id, v_application."First_Name", v_application."Middle_Name",
